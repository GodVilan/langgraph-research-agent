"""Re-verify the written artifact against what the builder claims about it.

Backs `make verify-dataset`. **Read the limits before trusting the green.**

WHAT THIS CHECKS. It loads the persisted JSON, resolves chunk ids from disk, re-reads the
corpus, and re-runs the check chain against the result. So it catches everything that can go
wrong *between* a correct decision and the artifact on disk: serialization loss, chunk-id
drift, a checksum that no longer matches, an item edited by hand, a field the writer dropped,
a gold chunk that has stopped existing. Its claim is narrow and worth stating exactly:

    the artifact matches what the builder claims about it.

WHAT IT NO LONGER CHECKS, AND WHY. It used to run its own copy of the chain, and that
independence is what found the first three defects — `build_factual` was running two of five
checks while the report described five. The fix was to collapse four divergent copies into
one ``classify_candidate``, which every builder and this verifier now call.

That fix removed the independence it depended on. Both paths now run the same code, so a
check that is *wrong*, or one that is *missing from the shared chain*, is invisible to both
identically. This gate can no longer find that class of defect at all.

WHAT CARRIES THE WEIGHT INSTEAD. The stratum x defect matrix in
``tests/test_check_matrix.py`` is now the sole evidence that the chain is correct. Its
fixtures are hand-authored and must stay that way: a fixture generated by the code that
classifies it is the reimplementation problem a third time, and the matrix would prove only
that the generator and the classifier agree.

What remains independent here is **input and timing**, not implementation — persisted bytes
rather than in-memory objects, disk rather than the builder's own index, after the fact
rather than during. That is a real and useful axis. It is not the axis it was.

Usage:
    python -m evals.verify_dataset evals/datasets/phase4.json
    python -m evals.verify_dataset evals/datasets/phase4.json --json
"""

from __future__ import annotations

import collections
import json
import sys
from pathlib import Path
from typing import Annotated, Any

import typer

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from evals.absence import load_corpus, verify_attribute_absent, verify_topic_absent
from evals.build_set import leaks
from evals.draft import banned_phrases_in
from evals.multihop import paper_text
from evals.schema import EvalSet, Stratum
from evals.verify_items import (
    GOLD_SET_CEILING,
    classify_candidate,
    conjunctive_discriminator,
    contrastive_premise,
    minimal_gold,
    unsupported_chunks,
)

app = typer.Typer(add_completion=False, help=__doc__)


def check_item(item: Any, by_id: dict[str, str]) -> list[tuple[str, str]]:
    """Every defect found in one item, as (check name, detail). Empty means clean."""
    found: list[tuple[str, str]] = []
    gold_texts = [by_id[g] for g in item.gold_chunk_ids if g in by_id]

    missing_chunks = [g for g in item.gold_chunk_ids if g not in by_id]
    if missing_chunks:
        found.append(("gold_chunk_exists", f"not in corpus: {missing_chunks}"))

    if item.stratum.expects_refusal:
        outcome = (
            verify_topic_absent(item.absent_term)
            if item.stratum is Stratum.UNANSWERABLE_TOPIC
            else verify_attribute_absent(item.anchor_paper_id, item.absent_term)
        )
        if not outcome.absent:
            found.append(("absence", outcome.reason))
        if item.gold_chunk_ids:
            found.append(("refusal_has_gold", "an unanswerable item carries gold chunks"))
        return found

    if item.stratum is Stratum.AMBIGUOUS:
        # Different contract: gold chunks are competing referents, not answer support.
        if not item.gold_chunk_ids:
            found.append(("ambiguous_referents", "no competing referents recorded"))
        return found

    # The same chain the builders run — literally the same function. The verifier having
    # its own copy is what let three defects through: the builder ran a subset, the
    # verifier ran a superset, and each reported itself complete.
    sources = list(item.provenance.source_paper_ids)
    papers = [paper_text(p, 40_000) for p in sources]
    present = {g: by_id[g] for g in item.gold_chunk_ids if g in by_id}
    verdict = classify_candidate(
        question=item.question,
        answer=item.gold_answer,
        gold_texts=gold_texts,
        paper_texts=papers,
        banned=banned_phrases_in(item.question),
        leaked=bool(gold_texts) and leaks(item.question, gold_texts[0]),
        source_paper_ids=sources,
        gold_by_paper={p: [t for g, t in present.items() if g.startswith(p)] for p in sources},
    )
    if verdict is not None:
        found.append(verdict)

    # The premise the figure-rarity threshold is derived from. If gold sets grow past it, the
    # coincidence budget behind `max_document_frequency` no longer holds, and that has to fail
    # here rather than silently make common figures count as evidence again.
    if len(item.gold_chunk_ids) > GOLD_SET_CEILING:
        found.append(
            (
                "gold_set_too_large",
                f"{len(item.gold_chunk_ids)} chunks; the figure-rarity threshold assumes at "
                f"most {GOLD_SET_CEILING}",
            )
        )

    dead = unsupported_chunks(item.gold_answer, present)
    if dead:
        found.append(("dead_gold_chunk", f"supports no claim the answer makes: {dead}"))

    # Redundancy, which `dead_gold_chunk` cannot see: three chunks supporting the same claim
    # are each individually justified and together inflate the Recall@k denominator.
    if item.gold_answer and present:
        minimal = minimal_gold(item.gold_answer, present, sources)
        surplus = sorted(set(present) - set(minimal))
        if surplus:
            found.append(("redundant_gold_chunk", f"support nothing the rest does not: {surplus}"))

    severity, why = contrastive_premise(item.question, item.gold_answer, sources)
    if severity == "review":
        found.append(("contrastive_premise", why))
    condition = conjunctive_discriminator(item.question)
    if condition:
        found.append(
            ("conjunctive_premise", f"needs one paper to satisfy both halves of: {condition}")
        )
    return found


@app.command()
def main(
    path: Annotated[Path, typer.Argument()] = Path("evals/datasets/phase4.json"),
    as_json: Annotated[bool, typer.Option("--json")] = False,
) -> None:
    evalset = EvalSet.read(path)
    by_id = {str(c["chunk_id"]): str(c["text"]) for c in load_corpus().chunks}

    defects: dict[str, list[tuple[str, str]]] = {}
    for item in evalset.items:
        found = check_item(item, by_id)
        if found:
            defects[item.item_id] = found

    by_stratum: dict[str, dict[str, int]] = collections.defaultdict(
        lambda: {"items": 0, "clean": 0, "defective": 0}
    )
    for item in evalset.items:
        row = by_stratum[item.stratum.value]
        row["items"] += 1
        row["defective" if item.item_id in defects else "clean"] += 1

    if as_json:
        typer.echo(
            json.dumps(
                {
                    "path": str(path),
                    "sha256": evalset.sha256,
                    "items": len(evalset.items),
                    "defective": len(defects),
                    "by_stratum": dict(by_stratum),
                    "defects": {k: [list(v) for v in vs] for k, vs in defects.items()},
                },
                indent=2,
            )
        )
        raise typer.Exit(1 if defects else 0)

    typer.echo(f"Independently re-verifying {path} ({len(evalset.items)} items)")
    typer.echo(f"  sha {evalset.sha256[:16]}  corpus {evalset.corpus_sha256[:12]}\n")
    typer.echo(f"{'stratum':28} {'items':>6} {'clean':>6} {'defective':>10}")
    for name, row in sorted(by_stratum.items()):
        typer.echo(f"{name:28} {row['items']:6d} {row['clean']:6d} {row['defective']:10d}")

    if defects:
        counts = collections.Counter(name for found in defects.values() for name, _ in found)
        typer.echo(f"\ndefects by check: {dict(counts)}\n")
        for item_id, found in sorted(defects.items())[:20]:
            for name, detail in found:
                typer.echo(f"  {item_id:10} {name:20} {detail[:80]}")
        typer.echo(
            typer.style(
                f"\nFAILED: {len(defects)} of {len(evalset.items)} items disagree with the "
                f"builder's report. The set does not freeze.",
                fg=typer.colors.RED,
            )
        )
        raise typer.Exit(1)

    typer.echo(
        typer.style(
            f"\nAGREED: the artifact and the builder's report concur on all "
            f"{len(evalset.items)} items.",
            fg=typer.colors.GREEN,
        )
    )


if __name__ == "__main__":
    app()
